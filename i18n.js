let lang = 'sv';

function detectLang() {
  const nav = (navigator.language || 'sv').slice(0, 2).toLowerCase();
  return LANGS[nav] ? nav : 'sv';
}

const locale = () => LANGS[lang].locale;

// Hämtar en text. Okända nycklar returneras som de är (så vanlig text kan skickas rakt igenom).
function t(key, vars = {}) {
  const text = (STRINGS[lang] && STRINGS[lang][key]) ?? STRINGS.sv[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? vars[name] : `{${name}}`));
}

// Fyller i alla statiska texter i HTML:en (data-i18n = text, data-i18n-html = med <kbd> m.m., data-i18n-aria = aria-label)
function applyStaticTexts() {
  document.documentElement.lang = lang;
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of document.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
}
